// 1. REQUIREMENT RECEIVED TEMPLATE (Recipient: Agency Owner)
// =========================================================
export interface RequirementReceivedParams {
  agency: BaseAgencyContext;
  requirementId: string;
  positionTitle: string;
  companyName: string;
  contactPerson?: string;
  source?: string;
  receivedDate?: string;
  baseUrl?: string;
}

export function generateRequirementReceivedTemplate(params: RequirementReceivedParams): RenderedEmail {
  const { agency, requirementId, positionTitle, companyName, contactPerson, source, receivedDate, baseUrl } = params;
  const appUrl = baseUrl || DEFAULT_BASE_URL;
  const title = `New Requirement Received - ${positionTitle}`;
  const ctaUrl = `${appUrl}/incoming-requirements/${requirementId}`;

  const htmlContent = `
    <p style="margin-top: 0;">A new client hiring requirement has been received and logged in your inbox pipeline.</p>

    <div style="background-color: #f1f5f9; border-left: 4px solid #0d3859; padding: 16px; border-radius: 6px; margin: 20px 0;">
      <table role="presentation" width="100%" border="0" cellspacing="0" cellpadding="4" style="font-size: 13px; color: #1e293b;">
        <tr><td width="35%" style="font-weight: 700; color: #475569;">Requirement ID:</td><td>REQ-${requirementId.slice(0, 8).toUpperCase()}</td></tr>
        <tr><td style="font-weight: 700; color: #475569;">Position Title:</td><td style="font-weight: 700; color: #0d3859;">${positionTitle}</td></tr>
        <tr><td style="font-weight: 700; color: #475569;">Company Name:</td><td>${companyName}</td></tr>
        <tr><td style="font-weight: 700; color: #475569;">Contact Person:</td><td>${contactPerson || 'N/A'}</td></tr>
        <tr><td style="font-weight: 700; color: #475569;">Source:</td><td>${source || 'Website Widget'}</td></tr>
        <tr><td style="font-weight: 700; color: #475569;">Received Date:</td><td>${receivedDate || new Date().toLocaleDateString('en-US')}</td></tr>
      </table>
    </div>

    <p>Please review the requirement details and assign a lead recruiter to start sourcing.</p>
  `;

  const textContent = `New Requirement Received - ${positionTitle}\n
Requirement ID: REQ-${requirementId.slice(0, 8).toUpperCase()}
Position: ${positionTitle}
Company: ${companyName}
Contact Person: ${contactPerson || 'N/A'}
Source: ${source || 'Website Widget'}
Received Date: ${receivedDate || new Date().toLocaleDateString('en-US')}

View Requirement: ${ctaUrl}`;

  return {
    subject: title,
    html: wrapMasterLayout(agency, title, htmlContent, { label: 'View Requirement', url: ctaUrl }),
    text: textContent
  };
}

