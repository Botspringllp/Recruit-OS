/**
 * RecruitOS Dynamic Email Template Engine (PHASE EM-01)
 * Generates dynamic, production-grade HTML and Plain Text emails for all platform events.
 * Fully multi-tenant aware with dynamic Agency branding and master layout system.
 */

export interface RenderedEmail {
  subject: string;
  html: string;
  text: string;
}

export interface BaseAgencyContext {
  agencyName?: string | null;
  logoUrl?: string | null;
  senderName?: string | null;
  replyToEmail?: string | null;
  contactEmail?: string | null;
  contactPhone?: string | null;
  websiteUrl?: string | null;
}

const DEFAULT_BASE_URL = process.env.NEXT_PUBLIC_APP_URL || 'http://localhost:3000';

/**
 * Master Email Layout Wrapper
 * Enforces responsive 700px max-width container, header branding, and RecruitOS footer.
 */
function wrapMasterLayout(
  agency: BaseAgencyContext,
  title: string,
  contentHtml: string,
  cta?: { label: string; url: string } | null
): string {
  const displayAgencyName = agency.agencyName || agency.senderName || 'RecruitOS Agency';
  const logoHtml = agency.logoUrl
    ? `<img src="${agency.logoUrl}" alt="${displayAgencyName}" style="max-height: 44px; width: auto; display: block; margin-bottom: 8px;" />`
    : '';

  const ctaButtonHtml = cta
    ? `
      <div style="margin: 32px 0 24px 0; text-align: center;">
        <a href="${cta.url}" target="_blank" style="background-color: #0d3859; color: #ffffff; font-family: 'Segoe UI', Roboto, Helvetica, Arial, sans-serif; font-size: 14px; font-weight: 800; padding: 14px 28px; text-decoration: none; border-radius: 8px; display: inline-block; box-shadow: 0 4px 6px -1px rgba(13, 56, 89, 0.2);">
          ${cta.label}
        </a>
      </div>
    `
    : '';

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${title}</title>
  <style>
    body { margin: 0; padding: 0; background-color: #f8fafc; font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif; -webkit-font-smoothing: antialiased; }
    table { border-collapse: collapse; }
    @media only screen and (max-width: 640px) {
      .container { width: 100% !important; padding: 12px !important; }
      .content-box { padding: 20px 16px !important; }
      .table-responsive { display: block !important; width: 100% !important; overflow-x: auto !important; }
    }
  </style>
</head>
<body style="margin: 0; padding: 24px 0; background-color: #f8fafc;">
  <table role="presentation" width="100%" border="0" cellspacing="0" cellpadding="0">
    <tr>
      <td align="center">
        <!-- 700px Container -->
        <table role="presentation" class="container" width="700" border="0" cellspacing="0" cellpadding="0" style="width: 700px; max-width: 700px; margin: 0 auto;">
          
          <!-- Header Branding -->
          <tr>
            <td style="padding: 16px 24px; background-color: #ffffff; border-top-left-radius: 12px; border-top-right-radius: 12px; border-bottom: 2px solid #e2e8f0;">
              <table role="presentation" width="100%" border="0" cellspacing="0" cellpadding="0">
                <tr>
                  <td>
                    ${logoHtml}
                    <div style="font-size: 20px; font-weight: 800; color: #0d3859; letter-spacing: -0.5px; text-transform: uppercase;">
                      ${displayAgencyName}
                    </div>
                  </td>
                  <td align="right" style="font-size: 11px; color: #64748b; font-weight: 600;">
                    Official Notification
                  </td>
                </tr>
              </table>
            </td>
          </tr>

          <!-- Main Body -->
          <tr>
            <td class="content-box" style="padding: 32px; background-color: #ffffff; border-bottom-left-radius: 12px; border-bottom-right-radius: 12px; box-shadow: 0 4px 12px rgba(15, 23, 42, 0.05);">
              
              <h2 style="margin: 0 0 20px 0; font-size: 20px; font-weight: 800; color: #0f172a; letter-spacing: -0.3px;">
                ${title}
              </h2>

              <div style="font-size: 14px; line-height: 1.6; color: #334155;">
                ${contentHtml}
              </div>

              ${ctaButtonHtml}

            </td>
          </tr>

          <!-- Footer -->
          <tr>
            <td style="padding: 24px 16px; text-align: center; font-size: 12px; color: #94a3b8; line-height: 1.5;">
              <p style="margin: 0 0 4px 0; font-weight: 600; color: #64748b;">
                ${displayAgencyName} ${agency.contactEmail ? `• ${agency.contactEmail}` : ''}
              </p>
              <p style="margin: 0;">
                This email was generated by <strong style="color: #0d3859;">RecruitOS</strong> Talent Platform
              </p>
            </td>
          </tr>

        </table>
      </td>
    </tr>
  </table>
</body>
</html>`;
}

